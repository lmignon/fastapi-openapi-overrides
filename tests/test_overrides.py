from enum import Enum
from typing import Any

import pytest
from fastapi import APIRouter, Depends, FastAPI, Header, Query, Security
from fastapi.security import OAuth2PasswordBearer
from fastapi.testclient import TestClient

from fastapi_openapi_overrides import document_dependency_overrides

oauth2_scheme = OAuth2PasswordBearer(tokenUrl="token", scopes={"me": "Read me"})


class Color(str, Enum):
    red = "red"
    blue = "blue"


def authenticated_user() -> str:
    """Abstract dependency: must be overridden by the application."""
    raise NotImplementedError()  # pragma: no cover


def header_user(x_user: str = Header()) -> str:
    return x_user


def oauth2_user(token: str = Security(oauth2_scheme, scopes=["me"])) -> str:
    return token


def color_user(color: Color = Query()) -> str:
    return color.value


def common_parameters(q: str, skip: int = 0, limit: int = 100) -> dict[str, Any]:
    return {"q": q}  # pragma: no cover


def simple_override(q: str | None = None) -> dict[str, Any]:
    return {"q": q}


def sub_dependency(k: str) -> str:
    return k


def override_with_sub(k: str = Depends(sub_dependency)) -> dict[str, Any]:
    return {"k": k}


def sub_dependency_override(other: int) -> str:
    return str(other)


router = APIRouter()
users_router = APIRouter(prefix="/users")


@users_router.get("/me")
def read_me(user: str = Depends(authenticated_user)) -> str:
    return user


@users_router.get("/search")
def search(commons: dict[str, Any] = Depends(common_parameters)) -> dict[str, Any]:
    return commons


@users_router.get("/admin")
def read_admin(user: str = Security(authenticated_user, scopes=["admin"])) -> str:
    return user


router.include_router(users_router)


def create_client(
    overrides: dict[Any, Any], document_overrides: bool = True
) -> TestClient:
    app = FastAPI()
    app.include_router(router, prefix="/api")
    app.dependency_overrides.update(overrides)
    if document_overrides:
        document_dependency_overrides(app)
    return TestClient(app)


def get_operation(client: TestClient, path: str) -> dict[str, Any]:
    return client.get("/openapi.json").json()["paths"][path]["get"]


def get_parameter_names(operation: dict[str, Any]) -> list[str]:
    return [parameter["name"] for parameter in operation.get("parameters", [])]


def test_without_overrides():
    """Without overrides, the schema is the one generated by FastAPI."""
    client = create_client({})
    reference_client = create_client({}, document_overrides=False)
    assert client.get("/openapi.json").json() == (
        reference_client.get("/openapi.json").json()
    )


@pytest.mark.parametrize("document_overrides", [True, False])
def test_header_override(document_overrides):
    client = create_client({authenticated_user: header_user}, document_overrides)
    operation = get_operation(client, "/api/users/me")
    if document_overrides:
        assert operation["parameters"] == [
            {
                "name": "x-user",
                "in": "header",
                "required": True,
                "schema": {"type": "string", "title": "X-User"},
            }
        ]
    else:
        # the bug fixed by this library: the override is not documented
        assert "parameters" not in operation
    assert "security" not in operation
    # the documented behavior is the one of the requests
    response = client.get("/api/users/me", headers={"x-user": "bob"})
    assert response.json() == "bob"
    assert client.get("/api/users/me").status_code == 422


def test_security_override():
    client = create_client({authenticated_user: oauth2_user})
    openapi = client.get("/openapi.json").json()
    operation = openapi["paths"]["/api/users/me"]["get"]
    assert "parameters" not in operation
    assert operation["security"] == [{"OAuth2PasswordBearer": ["me"]}]
    assert openapi["components"]["securitySchemes"] == {
        "OAuth2PasswordBearer": {
            "type": "oauth2",
            "flows": {"password": {"scopes": {"me": "Read me"}, "tokenUrl": "token"}},
        }
    }
    response = client.get("/api/users/me", headers={"Authorization": "Bearer tok"})
    assert response.json() == "tok"
    assert client.get("/api/users/me").status_code == 401


def test_override_with_definitions():
    """The models used by the overrides are added to the schema definitions."""
    client = create_client({authenticated_user: color_user})
    openapi = client.get("/openapi.json").json()
    operation = openapi["paths"]["/api/users/me"]["get"]
    assert operation["parameters"][0]["name"] == "color"
    assert operation["parameters"][0]["schema"] == {
        "$ref": "#/components/schemas/Color"
    }
    assert openapi["components"]["schemas"]["Color"]["enum"] == ["red", "blue"]
    assert client.get("/api/users/me?color=red").json() == "red"


def test_simple_override():
    client = create_client({common_parameters: simple_override})
    operation = get_operation(client, "/api/users/search")
    assert get_parameter_names(operation) == ["q"]
    assert operation["parameters"][0]["required"] is False
    assert client.get("/api/users/search").json() == {"q": None}


def test_override_with_sub_dependency():
    client = create_client({common_parameters: override_with_sub})
    operation = get_operation(client, "/api/users/search")
    assert get_parameter_names(operation) == ["k"]
    assert client.get("/api/users/search?k=v").json() == {"k": "v"}


def test_override_with_overridden_sub_dependency():
    client = create_client(
        {
            common_parameters: override_with_sub,
            sub_dependency: sub_dependency_override,
        }
    )
    operation = get_operation(client, "/api/users/search")
    assert get_parameter_names(operation) == ["other"]
    assert client.get("/api/users/search?other=1").json() == {"k": "1"}


def test_apps_sharing_a_router_with_different_overrides():
    header_client = create_client({authenticated_user: header_user})
    oauth2_client = create_client({authenticated_user: oauth2_user})
    header_operation = get_operation(header_client, "/api/users/me")
    oauth2_operation = get_operation(oauth2_client, "/api/users/me")
    assert get_parameter_names(header_operation) == ["x-user"]
    assert "security" not in header_operation
    assert get_parameter_names(oauth2_operation) == []
    assert oauth2_operation["security"] == [{"OAuth2PasswordBearer": ["me"]}]


def test_route_of_the_app():
    app = FastAPI()

    @app.get("/me")
    def me(user: str = Depends(authenticated_user)) -> str:
        return user

    app.dependency_overrides[authenticated_user] = header_user
    document_dependency_overrides(app)
    client = TestClient(app)
    assert get_parameter_names(get_operation(client, "/me")) == ["x-user"]


def test_schema_is_cached():
    app = FastAPI()
    app.include_router(router)
    document_dependency_overrides(app)
    app.dependency_overrides[authenticated_user] = header_user
    assert app.openapi() is app.openapi()
    assert get_parameter_names(app.openapi()["paths"]["/users/me"]["get"]) == ["x-user"]
    # the schema must be reset to take into account new overrides
    app.dependency_overrides[authenticated_user] = color_user
    assert get_parameter_names(app.openapi()["paths"]["/users/me"]["get"]) == ["x-user"]
    app.openapi_schema = None
    assert get_parameter_names(app.openapi()["paths"]["/users/me"]["get"]) == ["color"]


def test_security_override_with_scopes_of_the_overridden_dependency():
    """The scopes required by the overridden dependency are kept."""
    client = create_client({authenticated_user: oauth2_user})
    operation = get_operation(client, "/api/users/admin")
    assert operation["security"] == [{"OAuth2PasswordBearer": ["admin", "me"]}]
